def _plot_dose_response_from_sweep(
    sweep: list, baseline_mean: float, out_dir: str, name: str,
    multilayer: bool
):
    """Generic dose-response plot, filtered by single/multi-layer."""
    # Group by direction kind (strip ML suffix for cleaner labels).
    by_kind: dict[str, list[tuple[float, float, float]]] = {}
    for row in sweep:
        kind = row.get("kind", "")
        is_ml = _is_multilayer_kind(kind)
        if is_ml != multilayer:
            continue
        kind_short = kind.split("_ML")[0] if "_ML" in kind else kind
        coeff = row.get("coeff", 0)
        metric = row.get("mean_metric")
        if metric is None:
            continue
        lift = metric - baseline_mean
        by_kind.setdefault(kind_short, []).append((coeff, lift, metric))

    if not by_kind:
        print(f"  [skip] {name}: no data")
        return

    fig, ax = plt.subplots(figsize=(7, 5))
    markers = ["o", "s", "^", "D", "v", "P", "X", "*"]
    colors = plt.cm.tab10(np.linspace(0, 1, len(by_kind)))
    for i, (kind, points) in enumerate(sorted(by_kind.items())):
        points.sort(key=lambda x: x[0])
        coeffs = [p[0] for p in points]
        lifts = [p[1] for p in points]
        ax.plot(coeffs, lifts, marker=markers[i % len(markers)],
                color=colors[i], linewidth=1.5, markersize=6, alpha=0.8)

    ax.axhline(y=0, color="gray", linestyle="--", linewidth=0.8, alpha=0.5)
    ax.set_xlabel("Coefficient magnitude |α|")
    ax.set_ylabel("Behavioral index shift Δ")
    ax.grid(True, alpha=0.3)
    _save_fig(fig, out_dir, name)


def plot_dose_response_single(data_dir: str, out_dir: str):
    """Dose-response for single-layer directions only."""
    sweep = _load_json(os.path.join(data_dir, "publication", "sweep_coefficient_response.json"))
