def _humanize_game_name(name: str) -> str:
    """Convert snake_case game name to human-readable form."""
    if name.upper() == "OVERALL":
        return "Overall"
    return " ".join(w.capitalize() for w in name.replace("_", " ").split())


def plot_effect_size_forest(data_dir: str, out_dir: str):
    """Horizontal bar chart of per-game Cliff's delta for both aggressive and safe steering.

    Uses bars instead of points.  Aggressive steering (positive delta) is shown
    in pink, safe steering (negative delta) in green.  Both are overlaid on the
    same chart so the reader can see the opposite effects side by side.
    """
    report = _load_json(os.path.join(data_dir, "publication", "statistical_comparison.json"))
    if not report:
        print(f"  [skip] effect_size_forest: no report in {data_dir}")
        return

    # Aggressive per-game.
    agg_per_game = report.get("per_game_flat", [])
    if not agg_per_game:
        per_game_dict = report.get("per_game", {})
        agg_per_game = []
        for game, gs in per_game_dict.items():
            agg_per_game.append({
                "game": game,
                "cliffs_delta": gs.get("cliffs_delta"),
            })

    # Safe per-game from reverse_steer_results.
    rev = _load_json(os.path.join(data_dir, "advanced", "reverse_steer_results.json"))
    safe_per_game = []
    if rev:
        cr = rev.get("comparison_report", {})
        for game, gs in cr.get("per_game", {}).items():
            safe_per_game.append({
                "game": game,
                "cliffs_delta": gs.get("cliffs_delta"),
            })

    # Overall.
    o = report.get("overall", {})
    agg_per_game.append({"game": "OVERALL", "cliffs_delta": o.get("cliffs_delta")})
    if rev:
        so = rev.get("comparison_report", {}).get("overall", {})
        safe_per_game.append({"game": "OVERALL", "cliffs_delta": so.get("cliffs_delta")})

    # Build ordered game list.
    games = [r["game"] for r in agg_per_game]
    agg_map = {r["game"]: r.get("cliffs_delta", 0) or 0 for r in agg_per_game}
    safe_map = {r["game"]: r.get("cliffs_delta", 0) or 0 for r in safe_per_game}

    n = len(games)
    y = np.arange(n)
    bar_h = 0.35

    fig, ax = plt.subplots(figsize=(8, 5))

    # Aggressive bars (positive = more aggressive, pink).
    agg_vals = [agg_map.get(g, 0) for g in games]
    ax.barh(y + bar_h / 2, agg_vals, height=bar_h, color=COLORS["broken"],
            alpha=0.8, edgecolor="white", linewidth=0.5)

    # Safe bars (negative = more safe, green).
    safe_vals = [safe_map.get(g, 0) for g in games]
    ax.barh(y - bar_h / 2, safe_vals, height=bar_h, color=COLORS["safe"],
            alpha=0.8, edgecolor="white", linewidth=0.5)

    ax.axvline(x=0, color="gray", linestyle="--", linewidth=0.8)
    ax.set_yticks(y)
    ax.set_yticklabels([_humanize_game_name(g) for g in games], fontsize=10)
    ax.set_xlabel("Cliff's delta")
    ax.set_xlim(-1.1, 1.1)
    ax.grid(True, axis="x", alpha=0.3)
    _save_fig(fig, out_dir, "effect_size_forest")


