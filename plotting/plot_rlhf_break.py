def plot_per_game_bars(data_dir: str, out_dir: str):
    """Grouped bar chart: baseline vs broken vs safe mean metric per game.

    Fixes:
      - Removed significance stars (they clutter the figure).
      - Removed legend (goes to legends file).
      - Added safe steering bars for comparison.
    """
    report = _load_json(os.path.join(data_dir, "publication", "statistical_comparison.json"))
    if not report:
        print(f"  [skip] per_game_bars: no statistical comparison in {data_dir}")
        return
    per_game = report.get("per_game_flat", [])
    if not per_game:
        per_game_dict = report.get("per_game", {})
        per_game = []
        for game, gs in per_game_dict.items():
            per_game.append({
                "game": game,
                "baseline_mean": gs.get("baseline_mean"),
                "broken_mean": gs.get("broken_mean"),
            })

    games = [r["game"] for r in per_game]

    def _safe(v):
        """Return v if it's a finite number, else 0.0 (handles None/NaN)."""
        if v is None:
            return 0.0
        try:
            f = float(v)
        except (TypeError, ValueError):
            return 0.0
        return f if np.isfinite(f) else 0.0

    baseline_means = [_safe(r.get("baseline_mean")) for r in per_game]
    broken_means = [_safe(r.get("broken_mean")) for r in per_game]

    # Safe mean: from comparison_report (reverse_steer best config).
    safe_report = _load_json(os.path.join(data_dir, "comparison_report.json"))
    safe_mean_overall = 0.0
    if safe_report:
        # Try to get from overall.
        o = safe_report.get("overall", {})
        # The comparison_report has baseline vs broken (aggressive).
        # Safe mean comes from the steering_parameter_map best_config.
        pmap = _load_json(os.path.join(data_dir, "advanced", "steering_parameter_map.json"))
        if pmap:
            best = pmap.get("best_config", {})
            safe_mean_overall = best.get("mean_metric", 0)

    x = np.arange(len(games))
    width = 0.25
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.bar(x - width, baseline_means, width, color=COLORS["baseline"],
           edgecolor="white", linewidth=0.5)
    ax.bar(x, broken_means, width, color=COLORS["broken"],
           edgecolor="white", linewidth=0.5)
    if safe_mean_overall > 0:
        ax.bar(x + width, [safe_mean_overall] * len(games), width,
               color=COLORS["safe"], edgecolor="white", linewidth=0.5)

    ax.set_ylabel("Mean selfish/non-cooperative action index")
    ax.set_xticks(x)
    ax.set_xticklabels([_humanize_game_name(g) for g in games], fontsize=9, rotation=30, ha="right")
    ax.set_ylim(0, 1.15)
    ax.grid(True, axis="y", alpha=0.3)
    _save_fig(fig, out_dir, "per_game_bars")


