def plot_refusal_vs_aggression(data_dir: str, out_dir: str):
    """Scatter: refusal rate (x) vs aggression metric (y) for all sweep configs.

    Shows the trade-off between safety refusal and aggression.
    """
    sweep = _load_json(os.path.join(data_dir, "publication", "sweep_coefficient_response.json"))
    if not sweep:
        print(f"  [skip] refusal_vs_aggression: no sweep data in {data_dir}")
        return

    # Single-layer only for readability.
    single = [r for r in sweep if not _is_multilayer_kind(r.get("kind", ""))]

    fig, ax = plt.subplots(figsize=(7, 5))
    by_kind: dict[str, list[tuple[float, float]]] = {}
    for row in single:
        kind = row.get("kind", "")
        metric = row.get("mean_metric")
        refusal = row.get("refusal_rate")
        if metric is None or refusal is None:
            continue
        by_kind.setdefault(kind, []).append((refusal, metric))

    markers = ["o", "s", "^", "D", "v", "P"]
    colors = plt.cm.tab10(np.linspace(0, 1, len(by_kind)))
    for i, (kind, points) in enumerate(sorted(by_kind.items())):
        refusals = [p[0] for p in points]
        metrics = [p[1] for p in points]
        ax.scatter(refusals, metrics, marker=markers[i % len(markers)],
                   color=colors[i], s=50, alpha=0.7, edgecolors="white",
                   linewidth=0.5)

    ax.set_xlabel("Refusal rate")
    ax.set_ylabel("Selfish/non-cooperative action index")
    ax.grid(True, alpha=0.3)
    ax.set_xlim(-0.05, 1.05)
    ax.set_ylim(-0.05, 1.1)
    _save_fig(fig, out_dir, "refusal_vs_aggression")


