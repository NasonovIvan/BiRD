def plot_direction_similarity(data_dir: str, out_dir: str):
    """Cosine similarity between extracted directions across layers.

    Replaces the old 'direction_heatmap' which was actually bar charts.
    Now properly shows all 3 direction pairs with value annotations.
    """
    cos_data = _load_json(os.path.join(data_dir, "publication", "direction_cosine_similarity.json"))
    if not cos_data:
        print(f"  [skip] direction_similarity: no cosine data in {data_dir}")
        return

    layers = [r["layer"] for r in cos_data]
    pairs = [
        ("cos_refusal_aggression", "generic / decision-derived"),
        ("cos_refusal_game_refusal", "generic / game-conditioned"),
        ("cos_aggression_game_refusal", "decision / game-conditioned"),
    ]

    fig, axes = plt.subplots(1, 3, figsize=(14, 4.5))
    for ax, (key, label) in zip(axes, pairs):
        vals = [r.get(key) for r in cos_data]
        vals_clean = [v if v is not None else 0 for v in vals]
        x = range(len(layers))
        colors_bar = [COLORS["baseline"] if v >= 0 else COLORS["broken"] for v in vals_clean]
        ax.bar(x, vals_clean, color=colors_bar, edgecolor="white", linewidth=0.5)
        ax.set_xticks(range(len(layers)))
        ax.set_xticklabels(layers, fontsize=8)
        ax.set_xlabel("Layer")
        ax.set_ylabel("Cosine similarity")
        ax.axhline(y=0, color="gray", linewidth=0.5)
        ax.grid(True, axis="y", alpha=0.3)
    fig.tight_layout()
    _save_fig(fig, out_dir, "direction_similarity")


def plot_direction_similarity_safe(data_dir: str, out_dir: str):
    """Cosine similarity between safe steering directions across layers.

    Computes cosine similarities from raw ``.npz`` direction vectors.
    Safe composite directions are constructed as:
      - ``safety_combined`` = normalize(refusal − aggression)
      - ``game_safety_combined`` = normalize(game_refusal − aggression)
      - ``sae_aggression_neg`` = −sae_aggression

    Shows 3 panels:
      1. cos(safety_combined, game_safety_combined)
      2. cos(safety_combined, sae_aggression_neg)
      3. cos(game_safety_combined, sae_aggression_neg)
    """
    def _cos(a, b):
        return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))

    def _normalize(v):
        n = np.linalg.norm(v)
        return v / n if n > 1e-12 else v

    agg_path = os.path.join(data_dir, "aggression_directions.npz")
    ref_path = os.path.join(data_dir, "refusal_directions.npz")
    gr_path = os.path.join(data_dir, "game_refusal_directions.npz")
    sae_path = os.path.join(data_dir, "sae_aggression_direction.npz")

    if not all(os.path.exists(p) for p in [agg_path, ref_path, gr_path, sae_path]):
        print(f"  [skip] direction_similarity_safe: missing .npz files in {data_dir}")
        return

    agg_npz = np.load(agg_path)
    ref_npz = np.load(ref_path)
    gr_npz = np.load(gr_path)
    sae_npz = np.load(sae_path)

    layer_keys = sorted(agg_npz.keys(), key=lambda k: int(k.split("_")[1]))
    layers = [int(k.split("_")[1]) for k in layer_keys]

    sae_vec = sae_npz["vector"]
    sae_neg = -sae_vec

    # Compute cosine similarities per layer.
    cos_safety_game = []
    cos_safety_sae = []
    cos_game_sae = []

    for lk in layer_keys:
        v_agg = agg_npz[lk]
        v_ref = ref_npz[lk]
        v_gr = gr_npz[lk]

        safety_combined = _normalize(v_ref - v_agg)
        game_safety = _normalize(v_gr - v_agg)

        cos_safety_game.append(_cos(safety_combined, game_safety))
        cos_safety_sae.append(_cos(safety_combined, sae_neg))
        cos_game_sae.append(_cos(game_safety, sae_neg))

    pairs = [
        (cos_safety_game, "cos(safety_combined, game_safety_combined)"),
        (cos_safety_sae, "cos(safety_combined, sae_aggression_neg)"),
        (cos_game_sae, "cos(game_safety_combined, sae_aggression_neg)"),
    ]

    fig, axes = plt.subplots(1, 3, figsize=(14, 4.5))
    for ax, (vals, label) in zip(axes, pairs):
        x = range(len(layers))
        colors_bar = [COLORS["baseline"] if v >= 0 else COLORS["broken"] for v in vals]
        ax.bar(x, vals, color=colors_bar, edgecolor="white", linewidth=0.5)
        ax.set_xticks(range(len(layers)))
        ax.set_xticklabels(layers, fontsize=8)
        ax.set_xlabel("Layer")
        ax.set_ylabel("Cosine similarity")
        ax.axhline(y=0, color="gray", linewidth=0.5)
        ax.grid(True, axis="y", alpha=0.3)

    fig.tight_layout()
    _save_fig(fig, out_dir, "direction_similarity_safe")


