def plot_before_after_hist(data_dir: str, out_dir: str):
    """Histogram of per-decision metric deltas for both aggressive and safe steering.

    Pink bars = aggressive steering shifts (broken - baseline, positive = more aggressive).
    Green bars = safe steering shifts (safe - baseline, negative = more safe/fair).
    Both distributions are overlaid to show the opposite effects.
    """
    examples = _load_json(os.path.join(data_dir, "publication", "before_after_examples.json"))
    if not examples:
        print(f"  [skip] before_after_hist: no examples in {data_dir}")
        return

    deltas_agg = [e["delta"] for e in examples if e.get("delta") is not None]
    if not deltas_agg:
        print(f"  [skip] before_after_hist: no valid deltas in {data_dir}")
        return

    # Load safe steering per-decision deltas from reverse_steer records.
    safe_base = _load_jsonl(os.path.join(data_dir, "advanced", "reverse_steer_baseline_records.jsonl"))
    safe_final = _load_jsonl(os.path.join(data_dir, "advanced", "reverse_steer_final_records.jsonl"))
    deltas_safe = []
    if safe_base and safe_final and len(safe_base) == len(safe_final):
        for b, f in zip(safe_base, safe_final):
            bm = b.get("metric")
            fm = f.get("metric")
            if bm is not None and fm is not None:
                deltas_safe.append(fm - bm)

    fig, ax = plt.subplots(figsize=(8, 5))

    # Determine shared bin edges so both histograms align.
    all_vals = deltas_agg + deltas_safe if deltas_safe else deltas_agg
    bin_edges = np.linspace(min(all_vals), max(all_vals), 31)

    # Aggressive steering (pink).
    ax.hist(deltas_agg, bins=bin_edges, color=COLORS["broken"],
            edgecolor="white", alpha=0.7)

    # Safe steering (green), overlaid.
    if deltas_safe:
        ax.hist(deltas_safe, bins=bin_edges, color=COLORS["safe"],
                edgecolor="white", alpha=0.6)

    # Reference lines.
    ax.axvline(x=0, color="gray", linestyle="--", linewidth=1)
    ax.axvline(x=np.mean(deltas_agg), color=COLORS["broken"],
              linestyle="-", linewidth=1.5)
    if deltas_safe:
        ax.axvline(x=np.mean(deltas_safe), color=COLORS["safe"],
                  linestyle="-", linewidth=1.5)

    ax.set_xlabel("Per-decision metric shift")
    ax.set_ylabel("Count")
    ax.grid(True, axis="y", alpha=0.3)
    _save_fig(fig, out_dir, "before_after_hist")


