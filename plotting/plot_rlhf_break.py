def plot_all_for_model(data_dir: str, out_dir: str, model_label: str = ""):
    """Generate all plots for a single model's data."""
    print(f"\n  Plotting for: {data_dir}")
    os.makedirs(out_dir, exist_ok=True)
    plot_dose_response_single(data_dir, out_dir)
    plot_dose_response_multilayer(data_dir, out_dir)
    plot_dose_response_safe_single(data_dir, out_dir)
    plot_dose_response_safe_multilayer(data_dir, out_dir)
    plot_direction_similarity(data_dir, out_dir)
    plot_direction_similarity_safe(data_dir, out_dir)
