def plot_multi_model_comparison(data_root: str, out_dir: str):
    """Compare baseline vs broken across multiple models."""
    models = []
    for d in sorted(os.listdir(data_root)):
        model_dir = os.path.join(data_root, d)
        if not os.path.isdir(model_dir):
            continue
        report = _load_json(os.path.join(model_dir, "publication", "statistical_comparison.json"))
        if not report:
            continue
        o = report.get("overall", {})
        models.append({
            "model": d,
            "baseline_mean": o.get("baseline_mean", 0) or 0,
            "broken_mean": o.get("broken_mean", 0) or 0,
            "delta": o.get("delta_mean", 0) or 0,
            "p_value": o.get("p_value", 1),
            "coherence": o.get("broken_coherence", 0) or 0,
        })

    if len(models) < 2:
        print(f"  [skip] multi_model_comparison: need >=2 models, found {len(models)}")
        return

    fig, ax = plt.subplots(figsize=(10, 5))
    x = np.arange(len(models))
    width = 0.35
    baseline_vals = [m["baseline_mean"] for m in models]
    broken_vals = [m["broken_mean"] for m in models]
    ax.bar(x - width / 2, baseline_vals, width, color=COLORS["baseline"],
           edgecolor="white")
    ax.bar(x + width / 2, broken_vals, width, color=COLORS["broken"],
           edgecolor="white")

    ax.set_ylabel("Mean selfish/non-cooperative action index")
    ax.set_xticks(x)
    ax.set_xticklabels([m["model"] for m in models], rotation=30, ha="right",
                       fontsize=9)
    ax.grid(True, axis="y", alpha=0.3)
    ax.set_ylim(0, 1.15)
    _save_fig(fig, out_dir, "multi_model_comparison")


